#!/usr/bin/env python3
"""Render docs/agent_hub/BOARD.md from the job state (never edit it by hand).

Because the board is regenerated from task state, a claimed task leaves the
Open section by itself and the board cannot disagree with the task records.
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import job_adapters as ja  # noqa: E402

HEADER = "<!-- Generated by docs/agent_hub/tools/board.py; do not edit by hand. -->"


def _section(title: str, entries: list[dict], names: dict | None = None) -> list[str]:
    lines = ["", f"## {title}", ""]
    if not entries:
        return lines + ["_None._"]
    for e in sorted(entries, key=lambda e: str(e.get("task"))):
        # T-hub-028: the board shows T-<category>-NNN; the canonical id stays in the state files.
        tail = f"{e['line']}; {e['job']}" if e.get("job") else e["line"]
        lines.append(f"- **{ja.display_name(None, e['task'], names)}** {e['title']} ({tail})")
    return lines


def _merged(fn, repo, jobs: list) -> list[dict]:
    """Entries of every job on the board, each task once (tagged with its first job).  With no job
    on the board the backend is asked without a filter (the stub backend then lists its fixture)."""
    out, seen = [], set()
    for job in jobs or [None]:
        for e in fn(repo, job):
            if e["task"] not in seen:
                seen.add(e["task"])
                out.append(e)
    return out


def _job_block(repo, job: dict, state: dict) -> list[str]:
    lim = ja.job_limits(job)
    if not job.get("active"):
        status = f"ended {job.get('ended')}"
    elif state.get("paused"):
        status = f"active, PAUSED ({state.get('pause_reason')})"
    else:
        status = "active"
    wakes = state.get("wakes", [])
    per_agent: dict[str, int] = {}
    for w in wakes:
        per_agent[w["agent"]] = per_agent.get(w["agent"], 0) + 1
    fmt = lambda d: ", ".join(f"{k}={v}" for k, v in sorted(d.items())) or "none"  # noqa: E731
    return [
        f"### Job {job['id']}",
        "",
        f"- Goal: {job.get('goal')}",
        f"- Started: {job.get('started')}",
        f"- Status: {status}",
        *(["- Auto-end: on"] if job.get("auto_end") else []),
        f"- Limits: {fmt(lim)}",
        f"- Tasks posted: {ja.posted_count(repo, job)} of {lim['max_tasks_posted']}",
        f"- Wakes: {len(wakes)} of {lim['max_wakes_per_job']} (per agent: {fmt(per_agent)})",
        f"- Tokens (where reported): {fmt(state.get('tokens', {}))}",
    ]


def _held_lines(jobs: list, states: dict, names: dict) -> list[str]:
    """One line per abandoned process group that is still alive (see job_dispatcher)."""
    from job_dispatcher import Dispatcher  # late: job_dispatcher imports this module
    out = []
    for j in jobs:
        for agent, ent in sorted((states[j["id"]].get("abandoned") or {}).items()):
            if Dispatcher._group_alive(int(ent["pgid"])):
                out.append(f"- {agent} is held: the process group {ent['pgid']} of its wake on "
                           f"{ja.display_name(None, ent['task'], names)} ({j['id']}) is still running; "
                           f"no new {agent} wake starts in any job.")
    return out


def render_text(repo) -> str:
    repo = Path(repo)
    jobs = ja.visible_jobs(repo)
    states = {j["id"]: ja.load_state(repo, j["id"]) for j in jobs}
    lines = [HEADER, "", "# Job board", ""]
    if not jobs:
        lines.append("- No job has been started.")
    for n, job in enumerate(jobs):
        if n:
            lines.append("")
        lines += _job_block(repo, job, states[job["id"]])
    names = ja.name_map(repo)
    lines += _section("Open", _merged(ja.open_entries, repo, jobs), names)
    lines += _section("For the user to check", _merged(ja.user_check_entries, repo, jobs), names)
    lines += _section("Checked by the user (this job)", _merged(ja.checked_entries, repo, jobs), names)
    lines += _section("Questions for the user", _merged(ja.questions, repo, jobs), names)
    # T-hub-028 F1: a submitted task that waits for its reviewers (also after a user "not OK").
    lines += _section("In review", _merged(ja.in_review_entries, repo, jobs), names)
    lines += ["", "## Paused", ""]
    paused = [j for j in jobs if states[j["id"]].get("paused")]
    # T038 F1: an agent whose timed-out wake left a live process group is woken in no job.
    held = _held_lines(jobs, states, names)
    if paused:
        for j in paused:
            lines.append(f"- {j['id']} paused: {states[j['id']].get('pause_reason')}. "
                         f"Only the user can resume (`job.py resume --job {j['id']}`).")
    elif not held:
        lines.append("_Not paused._")
    lines += held
    # T-hub-028: a task that timed out twice stays Open and is not woken again; the job goes on.
    for j in jobs:
        for task, note in sorted((states[j["id"]].get("not_retried") or {}).items()):
            lines.append(f"- {ja.display_name(None, task, names)}: {note} ({j['id']})")
    return "\n".join(lines) + "\n"


def render(repo) -> bool:
    """Write BOARD.md if its content changed; return True when it did."""
    text = render_text(repo)
    path = ja.board_path(repo)
    try:
        if path.read_text(encoding="utf-8") == text:
            return False
    except FileNotFoundError:
        pass
    ja.write_text_atomic(path, text)
    return True


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    sub = ap.add_subparsers(dest="cmd", required=True)
    r = sub.add_parser("render", help="write docs/agent_hub/BOARD.md")
    r.add_argument("--repo", help="repository root (default: walk up from cwd to .git)")
    r.add_argument("--stdout", action="store_true", help="print instead of writing")
    args = ap.parse_args(argv)
    repo = ja.find_repo(args.repo)
    if args.stdout:
        sys.stdout.write(render_text(repo))
    else:
        changed = render(repo)
        print(f"{ja.board_path(repo)}: {'updated' if changed else 'unchanged'}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
